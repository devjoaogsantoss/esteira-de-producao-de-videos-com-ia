import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import ffmpeg from 'ffmpeg-static';
import {env,pipeline} from '@huggingface/transformers';
env.cacheDir=path.resolve('.cache/whisper');
const input=process.argv[2]??'public/audio/narracao-final-2026-fornecida.mp3';
const output=process.argv[3]??'review/provided-voice-transcript.json';
const pcm=spawnSync(ffmpeg,['-v','error','-i',input,'-ar','16000','-ac','1','-f','f32le','pipe:1'],{maxBuffer:16*1024*1024});
if(pcm.status!==0)throw new Error(pcm.stderr.toString());
const waveform=new Float32Array(pcm.stdout.buffer.slice(pcm.stdout.byteOffset,pcm.stdout.byteOffset+pcm.stdout.byteLength));
const model=process.argv[4]??'Xenova/whisper-base';
console.log(`Loading local multilingual ${model} model (CPU).`);
const transcriber=await pipeline('automatic-speech-recognition',model,{dtype:'q8',device:'cpu'});
console.log('Transcribing provided narration locally.');
const result=await transcriber(waveform,{language:'portuguese',task:'transcribe',return_timestamps:'word',chunk_length_s:25,stride_length_s:4});
fs.writeFileSync(output,JSON.stringify(result,null,2));
console.log(JSON.stringify({input,output,text:result.text},null,2));
await transcriber.dispose();
